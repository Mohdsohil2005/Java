// 3. Write a program to find the area of a circle with a given radius.

import java.util.*;

public class Q3{
    public static void main(String arg[]){

        float rad = 2.5f;
        float pi = 3.14f;

        float aoc = (pi * rad * rad);
        System.out.println("Area of circle is : "+aoc);
    }
}
