public class logical_op{
    public static void main(String arg[]){

        // Logical Operators

        System.out.println( (3>2) && (5>0) );    // Logical AND

        System.out.println( (3>2) || (5<0) );    // Logical OR

        System.out.println( !(3>2) );            // Logical NOT
    }
}